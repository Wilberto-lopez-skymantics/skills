#!/usr/bin/env node
'use strict';
/**
 * ui-specgen.cjs — generate the per-state UI smoke specs from the wireframe capture records (Stage 04).
 *
 *   node specs/.sdd/scripts/ui-specgen.cjs [--in specs/wireframes] [--out specs/fixtures/ui]
 *
 * For every <name>.capture.json that ui-capture.cjs wrote in Stage 03 (one per captured screen state), the
 * generated spec navigates to the recorded path, runs the recorded setup module, waits for the recorded
 * selector, asserts that every recorded data-testid is present, and records the observation for
 * `oracle.cjs diff-ui`. One test per frozen screen state: the floor of UI-4 coverage, written the same way by
 * every agent. Interaction tests (SPEC §14.3) are still written by hand next to it.
 *
 * Output: <out>/generated-wireframes.spec.ts — regenerated, never edited (a `covers` list in a capture record
 * becomes the test's `// covers:` comment). Zero dependencies; the generated file needs @playwright/test.
 */
const fs = require('fs');
const path = require('path');
const L = require('./sdd-lib.cjs');

function main() {
  const args = L.parseArgs(process.argv.slice(2));
  const root = typeof args.flags.root === 'string' ? path.resolve(args.flags.root) : L.defaultRoot();
  const inDir = path.resolve(root, typeof args.flags.in === 'string' ? args.flags.in : 'specs/wireframes');
  const outDir = path.resolve(root, typeof args.flags.out === 'string' ? args.flags.out : 'specs/fixtures/ui');
  if (!fs.existsSync(inDir)) { console.error(`${L.rel(root, inDir)}: no wireframes (Stage 03 captures them with ui-capture.cjs)`); return 2; }
  const records = fs.readdirSync(inDir).filter(f => f.endsWith('.capture.json')).sort()
    .map(f => { try { return JSON.parse(fs.readFileSync(path.join(inDir, f), 'utf8')); } catch (e) { console.error(`${f}: ${e.message}`); return null; } })
    .filter(Boolean);
  if (!records.length) { console.error(`${L.rel(root, inDir)}: no *.capture.json (re-capture with the current ui-capture.cjs)`); return 2; }
  const observeRel = path.relative(outDir, path.join(root, 'specs/.sdd/scripts/ui-observe.cjs')).split(path.sep).join('/');
  const q = s => JSON.stringify(String(s));
  const lines = [];
  lines.push(`// Generated by specs/.sdd/scripts/ui-specgen.cjs from ${L.rel(root, inDir)}/*.capture.json — regenerate, do not edit.`);
  lines.push(`// One smoke test per frozen screen state (UI-1, UI-4): navigate as captured, assert every recorded test id, observe for diff-ui.`);
  lines.push(`import { test, expect } from '@playwright/test';`);
  lines.push(`// eslint-disable-next-line @typescript-eslint/no-var-requires`);
  lines.push(`const { observe } = require(${q(observeRel.startsWith('.') ? observeRel : './' + observeRel)});`);
  lines.push(`const ROOT = ${q(path.relative(outDir, root).split(path.sep).join('/') || '.')};`);
  lines.push('');
  for (const r of records) {
    const ids = [...new Set(r.testids || [])];
    lines.push(`test(${q('wireframe: ' + r.name)}, async ({ page }) => {`);
    if (r.covers && r.covers.length) lines.push(`  // covers: ${r.covers.join(', ')}`);
    if (r.viewport) lines.push(`  await page.setViewportSize({ width: ${Number(r.viewport.width) || 1280}, height: ${Number(r.viewport.height) || 800} });`);
    lines.push(`  await page.goto(${q(r.path || '/')});`);
    if (r.setup) lines.push(`  { const m = require(require('path').resolve(__dirname, ROOT, ${q(r.setup)})); await (m.default || m)(page); }`);
    if (r.wait) lines.push(`  await page.waitForSelector(${q(r.wait)}, { state: 'visible' });`);
    for (const id of ids) lines.push(`  await expect(page.getByTestId(${q(id)}).first()).toBeAttached();`);
    lines.push(`  await observe(page, ${q(r.name)});`);
    lines.push('});');
    lines.push('');
  }
  fs.mkdirSync(outDir, { recursive: true });
  const out = path.join(outDir, 'generated-wireframes.spec.ts');
  fs.writeFileSync(out, lines.join('\n'));
  console.log(`Wrote ${L.rel(root, out)}: ${records.length} screen state(s), ${records.reduce((a, r) => a + new Set(r.testids || []).size, 0)} test-id assertions`);
  return 0;
}

process.exitCode = main();
